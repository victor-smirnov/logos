#!/usr/bin/env python3
"""Generate stdlib/lang/char/tables.logos — the Unicode property tables behind
char::is_alphabetic / is_lowercase / is_uppercase / is_numeric / is_whitespace /
is_control, as inclusive scalar-value ranges.

The ranges are read from rustc's own `char` methods (one pass over every scalar
value), so the tables carry exactly the Unicode version of the toolchain the
matrix compares against (rustc 1.98.1: Unicode 17.0.0).

    scripts/gen_char_tables.py [RUSTC]
"""
import os, subprocess, sys, tempfile

RUSTC = sys.argv[1] if len(sys.argv) > 1 else \
    '/home/victor/.rustup/toolchains/stable-x86_64-unknown-linux-gnu/bin/rustc'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'stdlib', 'lang', 'char', 'tables.logos')

PROPS = ['alphabetic', 'lowercase', 'uppercase', 'numeric', 'whitespace', 'control']

DUMP = r'''
fn main() {
    let props: [(&str, fn(char) -> bool); 6] = [
        ("alphabetic", char::is_alphabetic), ("lowercase", char::is_lowercase),
        ("uppercase", char::is_uppercase), ("numeric", char::is_numeric),
        ("whitespace", char::is_whitespace), ("control", char::is_control),
    ];
    println!("version {}.{}.{}", char::UNICODE_VERSION.0, char::UNICODE_VERSION.1, char::UNICODE_VERSION.2);
    for (name, f) in props.iter() {
        let mut out: Vec<(u32, u32)> = Vec::new();
        for c in (0u32..=0x10FFFF).filter_map(char::from_u32) {
            if !f(c) { continue; }
            let v = c as u32;
            match out.last_mut() {
                Some(r) if r.1 + 1 == v || (r.1 == 0xD7FF && v == 0xE000) => r.1 = v,
                _ => out.push((v, v)),
            }
        }
        print!("{}", name);
        for (a, b) in out { print!(" {}-{}", a, b); }
        println!();
    }
}
'''

def main():
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, 'dump.rs'); exe = os.path.join(d, 'dump')
        open(src, 'w').write(DUMP)
        subprocess.run([RUSTC, '--edition', '2021', '-O', '-o', exe, src], check=True)
        lines = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split('\n')
    version = lines[0].split()[1]
    tables = {}
    for ln in lines[1:]:
        if not ln: continue
        name, *rs = ln.split()
        tables[name] = [tuple(int(x) for x in r.split('-')) for r in rs]
    assert sorted(tables) == sorted(PROPS), sorted(tables)
    o = []
    o.append('// GENERATED by scripts/gen_char_tables.py from rustc\'s char methods — DO NOT EDIT.')
    o.append('// Unicode %s. Each table is inclusive scalar-value ranges, flattened as' % version)
    o.append('// [start0, end0, start1, end1, ...] in ascending order.')
    o.append('')
    o.append('package logos.lang.char;')
    o.append('')
    o.append('impl char {')
    o.append('    /// The Unicode version the property tables follow (as `core::char::UNICODE_VERSION`).')
    o.append('    pub const UNICODE_VERSION: (u8, u8, u8) = (%s);' %
             ', '.join('%su8' % x for x in version.split('.')))
    o.append('}')
    o.append('')
    for name in PROPS:
        rs = tables[name]
        flat = [x for r in rs for x in r]
        o.append('static %s: [u32; %d] = [' % (name.upper(), len(flat)))
        for i in range(0, len(flat), 8):
            o.append('    ' + ', '.join('0x%Xu32' % x for x in flat[i:i + 8]) + ',')
        o.append('];')
        o.append('')
    o.append('// `c` lies in one of `t`\'s ranges: binary search over the range starts.')
    o.append('fn in_ranges(t: &[u32], c: u32) -> bool {')
    o.append('    let mut lo: i64 = 0;')
    o.append('    let mut hi: i64 = t.len() / 2;')
    o.append('    while lo < hi {')
    o.append('        let mid: i64 = (lo + hi) / 2;')
    o.append('        if c < t[2 * mid] { hi = mid; }')
    o.append('        else if c > t[2 * mid + 1] { lo = mid + 1; }')
    o.append('        else { return true; }')
    o.append('    }')
    o.append('    return false;')
    o.append('}')
    open(OUT, 'w').write('\n'.join(o) + '\n')
    print('%s: Unicode %s, %s' % (os.path.relpath(OUT, ROOT), version,
          ', '.join('%s %d' % (n, len(tables[n])) for n in PROPS)))

main()
